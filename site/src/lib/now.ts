/**
 * «Сейчас» — в одном месте.
 *
 * Было захардкожено 2026-08-03 в двух файлах: удобно для прототипа, где
 * скриншот должен воспроизводиться, и прямая ошибка в собранном сайте —
 * обратный отсчёт на главной начинает врать на следующий же день.
 *
 * Оставлена одна лазейка: NEXT_PUBLIC_DEMO_DATE. Она нужна не разработке,
 * а портфолио — снимок экрана с «до фестиваля 41 день» рассказывает о работе,
 * а снимок с «завершено» не рассказывает ничего. На бою переменная не задана
 * и берутся настоящие часы.
 *
 * Вызывается только на сервере: в клиентском компоненте время сборки и время
 * гидратации разойдутся, и React справедливо на это пожалуется.
 */
export function now(): Date {
  const demo = process.env.NEXT_PUBLIC_DEMO_DATE
  if (demo) {
    const d = new Date(demo)
    if (!Number.isNaN(d.getTime())) return d
    console.warn(`[now] NEXT_PUBLIC_DEMO_DATE="${demo}" не читается как дата, беру часы`)
  }
  return new Date()
}
